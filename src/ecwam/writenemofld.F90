      SUBROUTINE WRITENEMOFLD(NEMO2WAM)

! ----------------------------------------------------------------------

!*    PURPOSE.
!     --------
!     APPEND THE NEMO -> WAM FIELDS TO THE PER-TASK LAW RESTART FILE THAT
!     SAVSTRESS WROTE SINCE THE LAST RECEIVE FROM NEMO (LLAWPEND).

!**   INTERFACE.
!     ----------
!     *CALL* *WRITENEMOFLD(NEMO2WAM)
!     *NEMO2WAM* FIELDS FROM OCEAN MODEL TO WAM, JUST RECEIVED

!     METHOD.
!     -------
!     A RESTART FROM THE LAW FILE REPEATS THE FORCING UPDATE THAT FOLLOWS IT,
!     WHICH USES THE NEMO FIELDS OF THE NEXT RECEIVE. SO SAVSTRESS ONLY RECORDS
!     THE FILE (CFILELAW, IJINFLAW:IJSUPLAW) AND THE FIELDS ARE APPENDED HERE,
!     ONCE RECEIVED: SST, ICE COVER, ICE THICKNESS, U AND V CURRENTS, AT THEIR
!     OWN KIND JWRO, AFTER THE HEADER AND THE NREAL RECORDS OF SAVSTRESS.
!     ONLY DONE FOR PER-TASK FILES (LRSTPARALW): THE RECORDS ARE IN THE POINT
!     ORDER OF THIS TASK, NOT IN THE 1-D DECOMPOSITION ORDER (IJ2NEWIJ) OF THE
!     SINGLE-FILE RESTARTS, SO A RESTART MUST USE THE SAME MODEL DECOMPOSITION.
!     READNEMOFLD READS THEM BACK.

! ----------------------------------------------------------------------

      USE PARKIND_WAVE, ONLY : JWIM, JWRO
      USE YOWDRVTYPE  , ONLY : OCEAN2WAVE

      USE YOWGRID  , ONLY : NCHNK, KIJL4CHNK, IJFROMCHNK
      USE YOWNEMOFLDS, ONLY : NNEMOREAL, LLAWPEND, IJINFLAW, IJSUPLAW, CFILELAW
      USE YOWTEST  , ONLY : IU06

      USE YOMHOOK  , ONLY : LHOOK,   DR_HOOK, JPHOOK

! ----------------------------------------------------------------------

      IMPLICIT NONE
#include "iwam_get_unit.intfb.h"

      TYPE(OCEAN2WAVE), INTENT(IN) :: NEMO2WAM


      INTEGER(KIND=JWIM) :: IUNIT
      INTEGER(KIND=JWIM) :: IFLD, IJ, ICHNK, KIJL, IJSB, IJLB

      REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
      REAL(KIND=JWRO), ALLOCATABLE, DIMENSION(:,:) :: ZLAW

! ----------------------------------------------------------------------

      IF (LHOOK) CALL DR_HOOK('WRITENEMOFLD',0,ZHOOK_HANDLE)

      ALLOCATE(ZLAW(IJINFLAW:IJSUPLAW, NNEMOREAL))
!$OMP PARALLEL DO SCHEDULE(STATIC) PRIVATE(ICHNK, KIJL, IJSB, IJLB)
      DO ICHNK = 1, NCHNK
        KIJL = KIJL4CHNK(ICHNK)
        IJSB = IJFROMCHNK(1, ICHNK)
        IJLB = IJFROMCHNK(KIJL, ICHNK)
        ZLAW(IJSB:IJLB,1) = NEMO2WAM%NEMOSST(1:KIJL,ICHNK)
        ZLAW(IJSB:IJLB,2) = NEMO2WAM%NEMOCICOVER(1:KIJL,ICHNK)
        ZLAW(IJSB:IJLB,3) = NEMO2WAM%NEMOCITHICK(1:KIJL,ICHNK)
        ZLAW(IJSB:IJLB,4) = NEMO2WAM%NEMOUCUR(1:KIJL,ICHNK)
        ZLAW(IJSB:IJLB,5) = NEMO2WAM%NEMOVCUR(1:KIJL,ICHNK)
      ENDDO
!$OMP END PARALLEL DO

      IUNIT = IWAM_GET_UNIT(IU06, CFILELAW(1:LEN_TRIM(CFILELAW)), 'a', 'u', 0, 'READWRITE')
      DO IFLD = 1, NNEMOREAL
        WRITE(IUNIT) (ZLAW(IJ,IFLD), IJ=IJINFLAW, IJSUPLAW)
      ENDDO
      CLOSE(IUNIT)

      DEALLOCATE(ZLAW)
      LLAWPEND = .FALSE.
      WRITE(IU06,*) ' WRITENEMOFLD: NEMO FIELDS APPENDED TO ', TRIM(CFILELAW)

      IF (LHOOK) CALL DR_HOOK('WRITENEMOFLD',1,ZHOOK_HANDLE)

      END SUBROUTINE WRITENEMOFLD
