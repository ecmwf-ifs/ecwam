      SUBROUTINE READNEMOFLD(IJINF, IJSUP, FILENAME, NEMO2WAM)

! ----------------------------------------------------------------------

!*    PURPOSE.
!     --------
!     READ THE NEMO -> WAM FIELDS THAT WRITENEMOFLD APPENDED TO A PER-TASK
!     LAW RESTART FILE, IF ANY, INTO NEMO2WAM.

!**   INTERFACE.
!     ----------
!     *CALL* *READNEMOFLD(IJINF, IJSUP, FILENAME, NEMO2WAM)
!     *IJINF*    INDEX OF THE FIRST POINT OF THE FILE
!     *IJSUP*    INDEX OF THE LAST POINT OF THE FILE
!     *FILENAME* FILENAME (INCLUDING PATH) OF THE LAW FILE OF THIS TASK
!     *NEMO2WAM* FIELDS FROM OCEAN MODEL TO WAM

!     METHOD.
!     -------
!     THE NNEMOREAL RECORDS (SST, ICE COVER, ICE THICKNESS, U AND V CURRENTS,
!     KIND JWRO) FOLLOW THE HEADER AND THE NREAL RECORDS WRITTEN BY SAVSTRESS
!     AND READ BY READSTRESS. THEY ARE IN THE POINT ORDER OF THE TASK THAT WROTE
!     THEM, SO THEY ARE ONLY VALID FOR PER-TASK FILES (LRSTPARALR) READ WITH THE
!     SAME MODEL DECOMPOSITION. THEY ARE ALL OR NONE: END OF FILE AT THE FIRST
!     ONE IS A FILE WITHOUT THEM (E.G. OLDER 16-FIELD RESTARTS), WHICH SETS
!     LREST_NEMO_ICE=.FALSE.; ANY OTHER READ ERROR ABORTS.

! ----------------------------------------------------------------------

      USE PARKIND_WAVE, ONLY : JWIM, JWRO
      USE YOWDRVTYPE  , ONLY : OCEAN2WAVE

      USE YOWCOUT  , ONLY : NREAL
      USE YOWGRID  , ONLY : NPROMA_WAM, NCHNK, KIJL4CHNK, IJFROMCHNK
      USE YOWNEMOFLDS, ONLY : NNEMOREAL, LREST_NEMO_ICE
      USE YOWTEST  , ONLY : IU06
      USE YOWABORT , ONLY : WAM_ABORT

      USE YOMHOOK  , ONLY : LHOOK,   DR_HOOK, JPHOOK

! ----------------------------------------------------------------------

      IMPLICIT NONE
#include "iwam_get_unit.intfb.h"

      INTEGER(KIND=JWIM), INTENT(IN) :: IJINF, IJSUP
      CHARACTER(LEN=296), INTENT(IN) :: FILENAME
      TYPE(OCEAN2WAVE), INTENT(INOUT) :: NEMO2WAM


      INTEGER(KIND=JWIM) :: LFILE, IUNIT, IOS
      INTEGER(KIND=JWIM) :: IFLD, IJ, ICHNK, KIJL, IJSB, IJLB

      REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
      REAL(KIND=JWRO), ALLOCATABLE, DIMENSION(:,:) :: RNEMO

! ----------------------------------------------------------------------

      IF (LHOOK) CALL DR_HOOK('READNEMOFLD',0,ZHOOK_HANDLE)

      LREST_NEMO_ICE = .FALSE.

      LFILE = LEN_TRIM(FILENAME)
      IUNIT = IWAM_GET_UNIT(IU06, FILENAME(1:LFILE), 'r', 'u', 0, 'READWRITE')

!     SKIP THE HEADER AND THE NREAL RECORDS (SEE READSTRESS)
      DO IFLD = 0, NREAL
        READ(IUNIT, IOSTAT=IOS)
        IF (IOS /= 0) THEN
          WRITE (IU06,*) ' READNEMOFLD: CANNOT SKIP RECORD ', IFLD+1, &
     &                   ' (IOSTAT=', IOS, ') OF ', FILENAME(1:LFILE)
          CALL WAM_ABORT("Truncated LAW restart file", __FILENAME__, __LINE__)
        ENDIF
      ENDDO

      ALLOCATE(RNEMO(IJINF:IJSUP, NNEMOREAL))
      DO IFLD = 1, NNEMOREAL
        READ(IUNIT, IOSTAT=IOS) (RNEMO(IJ,IFLD), IJ=IJINF,IJSUP)
        IF (IFLD == 1 .AND. IS_IOSTAT_END(IOS)) EXIT
        IF (IOS /= 0) THEN
          WRITE (IU06,*) ' READNEMOFLD: CANNOT READ NEMO RECORD ', IFLD, ' OF ', NNEMOREAL, &
     &                   ' (IOSTAT=', IOS, ') FROM ', FILENAME(1:LFILE)
          CALL WAM_ABORT("Incomplete or wrong-kind NEMO records in LAW restart file", &
     &                   __FILENAME__, __LINE__)
        ENDIF
        IF (IFLD == NNEMOREAL) LREST_NEMO_ICE = .TRUE.
      ENDDO

      CLOSE(IUNIT)

      IF (LREST_NEMO_ICE) THEN
!$OMP   PARALLEL DO SCHEDULE(STATIC) PRIVATE(ICHNK, KIJL, IJSB, IJLB)
        DO ICHNK = 1, NCHNK
          KIJL = KIJL4CHNK(ICHNK)
          IJSB = IJFROMCHNK(1, ICHNK)
          IJLB = IJFROMCHNK(KIJL, ICHNK)

          NEMO2WAM%NEMOSST(1:KIJL, ICHNK)     = RNEMO(IJSB:IJLB,1)
          NEMO2WAM%NEMOCICOVER(1:KIJL, ICHNK) = RNEMO(IJSB:IJLB,2)
          NEMO2WAM%NEMOCITHICK(1:KIJL, ICHNK) = RNEMO(IJSB:IJLB,3)
          NEMO2WAM%NEMOUCUR(1:KIJL, ICHNK)    = RNEMO(IJSB:IJLB,4)
          NEMO2WAM%NEMOVCUR(1:KIJL, ICHNK)    = RNEMO(IJSB:IJLB,5)

          IF (KIJL < NPROMA_WAM) THEN
            NEMO2WAM%NEMOSST(KIJL+1:NPROMA_WAM, ICHNK)     = NEMO2WAM%NEMOSST(1, ICHNK)
            NEMO2WAM%NEMOCICOVER(KIJL+1:NPROMA_WAM, ICHNK) = NEMO2WAM%NEMOCICOVER(1, ICHNK)
            NEMO2WAM%NEMOCITHICK(KIJL+1:NPROMA_WAM, ICHNK) = NEMO2WAM%NEMOCITHICK(1, ICHNK)
            NEMO2WAM%NEMOUCUR(KIJL+1:NPROMA_WAM, ICHNK)    = NEMO2WAM%NEMOUCUR(1, ICHNK)
            NEMO2WAM%NEMOVCUR(KIJL+1:NPROMA_WAM, ICHNK)    = NEMO2WAM%NEMOVCUR(1, ICHNK)
          ENDIF
        ENDDO
!$OMP   END PARALLEL DO
      ENDIF

      DEALLOCATE(RNEMO)

      WRITE(IU06,*) ' READNEMOFLD: NEMO FIELDS IN THE RESTART FILE: ', LREST_NEMO_ICE

      IF (LHOOK) CALL DR_HOOK('READNEMOFLD',1,ZHOOK_HANDLE)

      END SUBROUTINE READNEMOFLD
